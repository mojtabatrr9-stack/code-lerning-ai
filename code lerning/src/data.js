  function placementQuestions(catId, startTier) {
    var bank = QB[catId] || QB.lang;
    var byTier = { 1: [], 2: [], 3: [] };
    bank.forEach(function (q) { byTier[q.tier].push(q); });
    var out = [], ti = Math.max(1, Math.min(3, startTier || 2)), used = [];
    for (var i = 0; i < 5; i++) {
      var pool = byTier[ti].filter(function (q) { return used.indexOf(q) < 0; });
      if (!pool.length) { pool = bank.filter(function (q) { return used.indexOf(q) < 0; }); }
      if (!pool.length) break;
      var q = pool[Math.floor(rnd(hash(catId + i + ti) + i) * pool.length) % pool.length];
      used.push(q); out.push({ q: q, tier: ti });
      /* سطح بعدی بر اساس عملکرد تعیین می‌شود (اینجا فقط پیشنهاد اولیه است) */
      ti = ti + (i % 2 === 0 ? 1 : 0);
      if (ti > 3) ti = 3;
    }
    return out;
  }
